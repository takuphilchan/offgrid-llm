import { expect, test } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { InferenceEndpointManagement } from '../src/api/client';

test('actual isolated service keeps endpoint review durable and separate from legacy file maintenance', async ({page,request},testInfo)=>{
 const fixture=process.env.OFFGRID_E2E_ENDPOINT_FIXTURES;
 test.skip(!fixture||!process.env.OFFGRID_E2E_URL,'Requires disposable endpoint fixture wrapper, never installed configuration.');
 await page.addInitScript(()=>{localStorage.setItem('offgrid.onboarding.complete','true');localStorage.setItem('offgrid.locale','en');});
 await page.goto('/ui/#/models');
 const card=page.locator('.endpoint-model').filter({hasText:'endpoint:isolated-endpoint@r1'});
 await expect(card).toContainText('Review required');
 await expect(card.getByRole('button',{name:'Check connection',exact:true})).toBeDisabled();
 await expect(page.getByRole('button',{name:'Model actions: endpoint:isolated-endpoint@r1',exact:true})).toHaveCount(0);
 await card.getByRole('button',{name:'Review and enable',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('https://fixture.example.test');
 await page.getByRole('dialog').getByRole('button',{name:'Review and enable',exact:true}).click();
 await expect(card).toContainText('Access enabled');
 await expect(card).toContainText('configured credential is unavailable');
 const state=await (await request.get('/api/v2/inference-endpoints')).json() as InferenceEndpointManagement;
 expect(state.items[0]).toMatchObject({enabled:true,credential_ready:false,probe_allowed:false,review_required:false});
 expect(JSON.stringify(state)).not.toContain('OFFGRID_ISOLATED_UNAVAILABLE_CREDENTIAL');
 const unavailable=await request.post('/v1/chat/completions',{data:{model:'endpoint:isolated-endpoint@r1',messages:[{role:'user',content:'must not dispatch'}]}});
 expect(unavailable.status()).toBe(403);
 await card.getByRole('button',{name:'Disable access',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('already dispatched');
 await page.getByRole('dialog').getByRole('button',{name:'Disable access',exact:true}).click();
 await expect(card).toContainText('Access disabled');
 const saved=JSON.parse(await readFile(join(fixture!,'data','inference-endpoint-policy.json'),'utf8'));
 expect(saved.decisions['isolated-endpoint@r1'].enabled).toBe(false);
 const token=`endpoint-${Date.now()}`;await writeFile(join(fixture!,'restart-request'),token);
 await expect.poll(()=>readFile(join(fixture!,'restart-ack'),'utf8').catch(()=>''),{timeout:15_000}).toBe(token);
 await page.reload();await expect(card).toContainText('Access disabled');
 const configPath=join(fixture!,'endpoints.json'),configuration=JSON.parse(await readFile(configPath,'utf8'));
 configuration.endpoints[0].model_digest=`sha256:${'b'.repeat(64)}`;
 await writeFile(configPath,JSON.stringify(configuration));await page.reload();
 await expect(card).toContainText('Configuration changed. Restart');
 await expect(card.getByRole('button',{name:'Review and enable',exact:true})).toBeDisabled();
 await page.screenshot({path:testInfo.outputPath('endpoint-actual-service-review.png'),fullPage:true});
});
